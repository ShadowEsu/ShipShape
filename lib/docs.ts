/** Suggested answers for the App Store privacy label and Google Play Data safety form. */
export function storeAnswers(scan: ScanResult) {
  const rows: [string, string, string][] = [];
  if (has(scan, "feature:signup")) rows.push(["Contact info (email, name)", "App functionality", "Linked to the user"]);
  if (has(scan, "feature:image-upload")) rows.push(["User content (photos)", "App functionality", "Linked to the user"]);
  if (has(scan, "payments:card") || has(scan, "payments:iap")) rows.push(["Purchases", "App functionality", "Linked to the user"]);
  if (has(scan, "tracker:meta") || has(scan, "tracker:ads") || has(scan, "tracker:tiktok")) rows.push(["Identifiers and usage data", "Third party advertising; used for tracking", "Linked to the user"]);
  for (const name of ["google-analytics", "mixpanel", "amplitude", "segment", "posthog", "hotjar", "clarity"]) {
    if (has(scan, `tracker:${name}`)) {
      rows.push(["Usage data and diagnostics", "Analytics", "Check the SDK settings"]);
      break;
    }
  }
  return `${banner(scan)}
# Store privacy answers

| Data type | Purpose | Linked to user |
| --- | --- | --- |
${rows.length ? rows.map((r) => `| ${r.join(" | ")} |`).join("\n") : "| No data collected found | | |"}

Check each SDK's own privacy documentation; SDKs can collect more than your code calls directly.
`;
}
